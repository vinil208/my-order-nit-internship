// Small dependency-free PDF writer. All amounts use INR to remain readable in base PDF fonts.
const clean = (s) =>
  String(s)
    .normalize("NFKD")
    .replace(/[^\x20-\x7e]/g, " ")
    .replace(/([\\()])/g, "\\$1");
export function pdf(title, lines) {
  const wrapped = [];
  for (const line of lines) {
    let text = String(line);
    while (text.length > 94) {
      let cut = text.lastIndexOf(" ", 94);
      if (cut < 20) cut = 94;
      wrapped.push(text.slice(0, cut));
      text = text.slice(cut).trimStart();
    }
    wrapped.push(text);
  }
  const pages = [];
  for (let i = 0; i < Math.max(wrapped.length, 1); i += 46)
    pages.push(wrapped.slice(i, i + 46));
  const objects = [];
  const add = (s) => {
    objects.push(s);
    return objects.length;
  };
  add("<< /Type /Catalog /Pages 2 0 R >>");
  add("");
  add("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>");
  const ids = [];
  pages.forEach((ls, index) => {
    const stream =
      `BT /F1 20 Tf 44 790 Td (${clean(title)}) Tj /F1 10 Tf 0 -26 Td (My Order | Demo food factory | Tamil Nadu) Tj 0 -28 Td ` +
      ls.map((l) => `(${clean(l)}) Tj 0 -15 Td`).join("\n") +
      ` ET BT /F1 9 Tf 44 28 Td (Page ${index + 1} of ${pages.length} | Generated by My Order) Tj ET`;
    const sid = add(
      `<< /Length ${Buffer.byteLength(stream)} >>\nstream\n${stream}\nendstream`,
    );
    ids.push(
      add(
        `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 3 0 R >> >> /Contents ${sid} 0 R >>`,
      ),
    );
  });
  objects[1] = `<< /Type /Pages /Count ${ids.length} /Kids [${ids.map((i) => `${i} 0 R`).join(" ")}] >>`;
  let output = "%PDF-1.4\n",
    offsets = [0];
  objects.forEach((o, i) => {
    offsets.push(Buffer.byteLength(output));
    output += `${i + 1} 0 obj\n${o}\nendobj\n`;
  });
  const start = Buffer.byteLength(output);
  output +=
    `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n` +
    offsets
      .slice(1)
      .map((n) => String(n).padStart(10, "0") + " 00000 n \n")
      .join("") +
    `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${start}\n%%EOF`;
  return Buffer.from(output);
}
export function csv(rows) {
  if (!rows.length) return "No records in this date range\r\n";
  const keys = Object.keys(rows[0]);
  const cell = (value) => {
    let s = String(value ?? "");
    if (/^[=+@\t\r]/.test(s) || (/^-/.test(s) && !/^-[\d.]+$/.test(s)))
      s = "'" + s;
    return '"' + s.replaceAll('"', '""') + '"';
  };
  return (
    "\uFEFF" +
    [keys, ...rows.map((r) => keys.map((k) => r[k]))]
      .map((r) => r.map(cell).join(","))
      .join("\r\n")
  );
}
